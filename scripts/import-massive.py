# Pulls a small, aligned set of human-written utterances from Amazon MASSIVE 1.1
# (CC BY 4.0, https://github.com/alexa/massive) and writes src/lib/massive-examples.ts.
# Usage: python3 scripts/import-massive.py /path/to/1.1/data
# Only intents that clearly match a farm-visit category are used; unrelated
# everyday intents become extra "other" examples (realistic negatives).
import json, sys, re

DATA = sys.argv[1]
LOCALES = {"en": "en-US", "fr": "fr-FR", "de": "de-DE", "es": "es-ES", "it": "it-IT"}
MAP = {  # MASSIVE intent -> (our category, how many aligned rows)
    "transport_taxi": ("transport", 6),
    "transport_query": ("transport", 4),
    "takeaway_order": ("meals", 6),
    "general_greet": ("other", 3),
    "general_quirky": ("other", 3),
    "weather_query": ("other", 3),
}
BAD = re.compile(r"\b(alexa|olly|google|siri|uber|lyft|deliveroo|grubhub|domino|mcdonald|subway|app)\b", re.I)

rows = {k: {} for k in LOCALES}
for short, loc in LOCALES.items():
    for line in open(f"{DATA}/{loc}.jsonl", encoding="utf-8"):
        r = json.loads(line)
        if r["partition"] == "train" and r["intent"] in MAP:
            rows[short][r["id"]] = r

picked = []
for intent, (cat, n) in MAP.items():
    cands = sorted(
        (r for r in rows["en"].values() if r["intent"] == intent),
        key=lambda r: int(r["id"]),
    )
    seen, k = set(), 0
    for r in cands:
        u = r["utt"]
        words = len(u.split())
        if BAD.search(u) or not 4 <= words <= 12 or u in seen: continue
        if not all(r["id"] in rows[l] and not BAD.search(rows[l][r["id"]]["utt"]) for l in LOCALES): continue
        seen.add(u); k += 1
        picked.append((cat, intent, r["id"]))
        if k >= n: break

out = ["// GENERATED by scripts/import-massive.py — do not edit by hand.",
       "// Source: Amazon MASSIVE 1.1, train split, CC BY 4.0 (FitzGerald et al., 2022).",
       "// Human-written assistant requests, aligned across languages by MASSIVE id.",
       'import type { Category } from "./taxonomy";', "",
       "export const MASSIVE_EXAMPLES: { category: Category; intent: string; id: string; text: Record<string, string> }[] = ["]
for cat, intent, i in picked:
    text = {l: rows[l][i]["utt"] for l in LOCALES}
    out.append(f"  {{ category: {json.dumps(cat)}, intent: {json.dumps(intent)}, id: {json.dumps(i)}, text: {json.dumps(text, ensure_ascii=False)} }},")
out.append("];")
open("src/lib/massive-examples.ts", "w", encoding="utf-8").write("\n".join(out) + "\n")
print(len(picked), "rows")
